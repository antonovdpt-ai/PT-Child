// OFFLINE ONLY: the reference comes from checked-in migrations in a disposable
// PGlite instance. There is no database URL, network input or live SQL capture.
import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {pathToFileURL} from 'node:url';
import {createFullParentSchemaFixture,currentParentMigrations} from '../../tests/parent-full-schema-fixture.mjs';
const root=new URL('../../',import.meta.url);
const parentMigrations=[
 '20261003_008_parent_portal_identity.sql','20261003_009_parent_portal_publications.sql',
 '20261003_010_parent_publication_artifacts.sql','20261003_011_parent_role_boundaries.sql',
 '20261003_012_parent_publication_archive.sql','20261006_013_goal_parent_sync.sql'
];
const sourceFiles=currentParentMigrations;
export const policyTables=['app_user_roles','legal_document_versions','parent_child_access','parent_invitations','parent_consent_audit','parent_signup_reservations','parent_reports','parent_session_reports','parent_session_report_media','parent_goal_publications','parent_notifications'];
// pg_get_functiondef includes the COMPLETE body, signature/defaults/return type,
// language, volatility, security, search_path/config and other function attributes.
// Keep literal whitespace and case: normalizing it can alter quoted source text.
export const functionDefinitionQuery=`select p.proname name, p.oid::regprocedure::text signature, pg_get_userbyid(p.proowner) owner,
 encode(sha256(convert_to(pg_get_functiondef(p.oid),'UTF8')),'hex') definition_sha256,
 coalesce((select jsonb_agg(jsonb_build_object('role',case when a.grantee=0 then 'PUBLIC' else pg_get_userbyid(a.grantee) end,'privilege',a.privilege_type,'grantable',a.is_grantable) order by case when a.grantee=0 then 'PUBLIC' else pg_get_userbyid(a.grantee) end collate "C",a.privilege_type,a.is_grantable)
 from aclexplode(coalesce(p.proacl,acldefault('f',p.proowner))) a where a.grantee<>p.proowner),'[]'::jsonb) grants
 from pg_proc p where p.pronamespace='public'::regnamespace and p.proname=any($1::text[]) order by p.proname collate "C",p.oid::regprocedure::text collate "C"`;
export const policyDefinitionQuery=`select schemaname,tablename,policyname,permissive,roles,cmd,qual,with_check
 from pg_policies where schemaname='public' and tablename=any($1::text[])
 order by tablename collate "C",policyname collate "C"`;
export async function generateReference() {
 const sources=new Map();
 for(const file of sourceFiles)sources.set(file,await readFile(new URL('supabase/migrations/'+file,root),'utf8'));
 // Scope is discovered from approved migration declarations, never live names.
 const names=[...new Set(['account_is_active',...parentMigrations.flatMap(file=>[...sources.get(file).matchAll(/create or replace function public\.(\w+)\(/gi)].map(m=>m[1]))])].sort();
 const h=await createFullParentSchemaFixture({migrations:sourceFiles});
 try {
  await h.db.exec('set search_path=pg_catalog,public');
  const functions=await h.query(functionDefinitionQuery,[names]);
  if(functions.length!==names.length)throw Error('Missing/overloaded reviewed function');
  const policies=await h.query(policyDefinitionQuery,[policyTables]);
  const reference={functions,policies};
  const provenance=sourceFiles.map(file=>`-- ${file} sha256=${createHash('sha256').update(sources.get(file)).digest('hex')}`).join('\n');
  return `-- GENERATED by node ops/security/generate-parent-portal-definition-reference.mjs\n-- Offline reference from reviewed repo migrations; NEVER regenerate from live SQL.\n-- Exact catalog formatting is fail-closed: engine differences require review.\n${provenance}\n`+String.raw`do $verify_definitions$
declare
 expected jsonb := $reviewed_reference$`+JSON.stringify(reference,null,2)+String.raw`$reviewed_reference$::jsonb;
 actual jsonb;
 names text[];
 tables text[] := array[`+policyTables.map(t=>`'${t}'`).join(',')+String.raw`];
begin
 select array_agg(value->>'name') into names from jsonb_array_elements(expected->'functions');
 select coalesce(jsonb_agg(to_jsonb(definition)),'[]'::jsonb) into actual from (
 `+functionDefinitionQuery.replace('$1::text[]','names')+String.raw`
 ) definition;
 if actual is distinct from expected->'functions' then
  raise exception 'STOP: unreviewed parent security function definition/grants drift';
 end if;
 select coalesce(jsonb_agg(to_jsonb(definition)),'[]'::jsonb) into actual from (
 `+policyDefinitionQuery.replace('$1::text[]','tables')+String.raw`
 ) definition;
 if actual is distinct from expected->'policies' then
  raise exception 'STOP: unreviewed parent publication/identity policy set or definition drift';
 end if;
end; $verify_definitions$;
`;
 }finally{await h.db.close();}
}
if(process.argv[1]&&import.meta.url===pathToFileURL(process.argv[1]).href) {
 await writeFile(new URL('supabase/verification/verify_parent_portal_definitions.sql',root),await generateReference());
 console.log('PARENT_PORTAL_DEFINITION_REFERENCE_GENERATED_FROM_REPO_SOURCES');
}
